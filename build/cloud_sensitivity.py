"""Sensitivity of the all-sky estimate to the assumed cloud-deck height.  Writes docs/cloud_sensitivity.md.

For each deck height the grey optical depth is re-tuned to the same observed longwave cloud effect (27.9 W m-2), then the
all-sky halocarbon radiative efficiencies and the CO2 doubling forcing are recomputed.  Needs the cached cross-sections.
Run after build/build_spectra.py:  python build/cloud_sensitivity.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_spectra as B  # noqa: E402
from radforce.forcing.halogens import radiative_efficiency  # noqa: E402
from radforce.spectra import atmosphere as A  # noqa: E402
from radforce.spectra import rt  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "docs" / "cloud_sensitivity.md"
MOLS = ["CFC-11", "CFC-12", "HCFC-22", "HFC-134a", "HFC-23", "SF6", "CF4", "CCl4"]


def main() -> None:
    at = B.Atmos()
    tau0 = at.tau(at.base_cols)
    edges = list(at.ref.z_edges_km)
    clear = rt.total(at.nu, at.flux(tau0))
    tm = {m: at.tau(at.base_cols, 1.0, {m: 10.0}) for m in MOLS}
    t2 = tau0 + at.sig["CO2"] * at.base_cols["CO2"][:, None]
    rows = []
    for zc in (1.5, 2.5, 5.5, 7.5, 9.0):
        at.deck = int(np.searchsorted(edges, zc, side="right") - 1)
        try:
            info = at.calibrate_cloud(tau0)
        except ValueError:
            rows.append((zc, None, None, None))
            continue
        def allsky_olr(t):
            return rt.total(at.nu, at.allsky(t)[0])
        base = allsky_olr(tau0)
        res = {m: (base - allsky_olr(tm[m])) / 0.01 / radiative_efficiency(m) for m in MOLS}
        f2 = base - allsky_olr(t2)
        rows.append((zc, info["tau_c"], res, f2))
        print(zc, info["tau_c"], np.mean(list(res.values())), f2, flush=True)
    L = ["# Cloud-deck height sensitivity (auto-generated by `build/cloud_sensitivity.py`)", "",
         f"The all-sky estimate uses one grey cloud deck (cover {B.CLOUD_COVER}).  For each deck height the opacity is re-tuned so the model "
         f"longwave cloud effect equals {B.LW_CRE_TARGET} W m-2 (CERES EBAF Ed4.0).  Entries: all-sky radiative efficiency / AR6 value, and the "
         "all-sky top-of-atmosphere forcing of doubled CO2 (clear sky: "
         f"{rt.total(at.nu, at.flux(tau0)) - rt.total(at.nu, at.flux(t2)):.2f} W m-2).", "",
         "| deck layer (km) | tau_c | " + " | ".join(MOLS) + " | mean | CO2 2x all-sky |", "|" + "---|" * (len(MOLS) + 4)]
    for zc, tc, res, f2 in rows:
        z0 = edges[int(np.searchsorted(edges, zc, side='right') - 1)]
        z1 = edges[int(np.searchsorted(edges, zc, side='right'))]
        if res is None:
            L.append(f"| {z0:.0f}-{z1:.0f} | cannot match (even a black deck is too weak) |" + " |" * (len(MOLS) + 2))
            continue
        L.append(f"| {z0:.0f}-{z1:.0f} | {tc:.2f} | " + " | ".join(f"{res[m]:.2f}" for m in MOLS) + f" | {np.mean(list(res.values())):.2f} | {f2:.2f} |")
    L += ["", "A low deck cannot reach the observed cloud effect (low clouds are too warm), which is why the default is mid-troposphere.  "
          "The spread across heights that can match the observation indicates the structural uncertainty of the all-sky estimate.", ""]
    OUT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
