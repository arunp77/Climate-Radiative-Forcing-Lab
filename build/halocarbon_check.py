"""Write docs/halocarbon_check.md from the built tables (web/public/data/spectra/olr_halo.json, gases.json).

Run after build/build_spectra.py:  python build/halocarbon_check.py

For each halocarbon the radiative efficiency (forcing per ppb, from a 10 ppt perturbation uniformly mixed into the
1750 US-standard atmosphere) is compared with AR6 Table 7.SM.7.  A missing absorption band would make one molecule
an outlier; the common clear-sky excess over AR6 is the cloud effect on window absorbers.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "web" / "public" / "data" / "spectra"
OUT = ROOT / "docs" / "halocarbon_check.md"


def main() -> None:
    halo = json.loads((D / "olr_halo.json").read_text())
    meta = json.loads((D / "gases.json").read_text())
    c = halo["cloud"]
    rows = []
    for g, v in halo["gases"].items():
        m = meta[g]
        cov = f"{min(a for a, _ in m['coverage']):.0f}-{max(b for _, b in m['coverage']):.0f}"
        rows.append((g, v["re_clear"], v["re_all"], v["re_ar6"], cov, m["datasets"][0]))
    lines = ["# Halocarbon cross-section check (auto-generated by `build/halocarbon_check.py`)", "",
             "Radiative efficiency (W m-2 ppb-1) computed from the HITRAN cross-sections versus AR6 Table 7.SM.7 "
             "(all-sky, stratosphere-adjusted).  Model: 1750 US-standard atmosphere with the MT_CKD water-vapour "
             "continuum, 10 ppt of the gas mixed uniformly, instantaneous top-of-atmosphere forcing.", "",
             f"* **clear sky** = no clouds;",
             f"* **all-sky estimate** = (1 - {c['cover']}) x clear + {c['cover']} x grey cloud deck at {c['deck_km'][0]:.0f}-{c['deck_km'][1]:.0f} km, "
             f"optical depth {c['tau_c']:.2f}, tuned so the model longwave cloud effect is {c['model_lw_cre']:.1f} W m-2 "
             f"(CERES EBAF Ed4.0: {c['target_lw_cre']}).  The AR6 values play no part in this tuning, so the comparison is an independent test.", "",
             "| Molecule | clear sky | all-sky est. | AR6 | clear/AR6 | all-sky/AR6 | measured range (cm-1) | main data set |",
             "|---|---|---|---|---|---|---|---|"]
    for g, cl, al, ar, cov, ds in rows:
        lines.append(f"| {g} | {cl:.3f} | {al:.3f} | {ar:.3f} | {cl / ar:.2f} | {al / ar:.2f} | {cov} | "
                     f"{ds['range'][0]}-{ds['range'][1]}, {ds['files']} files |")
    a = np.array([al / ar for _, _, al, ar, *_ in rows])
    k = np.array([cl / ar for _, cl, _, ar, *_ in rows])
    lines += ["", f"Clear-sky/AR6: {k.min():.2f}-{k.max():.2f} (mean {k.mean():.2f}).  All-sky estimate/AR6: {a.min():.2f}-{a.max():.2f} "
              f"(mean {a.mean():.2f}, standard deviation {a.std():.2f}).", "",
             "Interpretation: the ratios cluster tightly, so no individual data set is missing a band.  The all-sky estimate removes most of the "
             "clear-sky excess; the residual reflects the simplicity of a one-deck cloud model, the single US-standard profile, the "
             "uniform vertical distribution of the halocarbons and the absence of stratospheric adjustment (which would raise our values).  "
             "Deck-height sensitivity: see `docs/cloud_sensitivity.md`.", ""]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
