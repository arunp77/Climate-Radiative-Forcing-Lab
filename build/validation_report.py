"""Generate docs/validation.md: every physics check against its published reference."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from radforce import wmghg_forcing, co2_forcing
from radforce.constants import PREINDUSTRIAL_1750 as PI
from radforce.data import ar6_concentrations, ar6_erf
from radforce.forcing.halogens import halogen_forcing_year
from radforce.forcing.nonghg import historical_state, non_ghg_erf

OUT = Path(__file__).resolve().parents[1] / "docs" / "validation.md"


def main() -> None:
    conc, ar6 = ar6_concentrations(), ar6_erf()
    row = ar6.loc[2019]
    f = wmghg_forcing(*conc.loc[2019, ["CO2", "CH4", "N2O"]].values)
    h = halogen_forcing_year(2019)
    lines = [
        "# Validation report (auto-generated by `build/validation_report.py`)",
        "",
        "Reference: IPCC AR6 WG1 Ch.7 ERF series (Smith et al.) and AR6 Annex III concentrations. "
        "Forcing is relative to 1750, year 2019.",
        "",
        "| Quantity | radforce (W m-2) | AR6 (W m-2) | difference |",
        "|---|---|---|---|",
    ]
    for name, mine, ref in (
        ("CO2", f["CO2"], row.co2),
        ("CH4", f["CH4"], row.ch4),
        ("N2O", f["N2O"], row.n2o),
        ("Halogenated (computed species only)", h["total"], row.other_wmghg),
    ):
        lines.append(f"| {name} | {mine:.3f} | {ref:.3f} | {mine - ref:+.4f} |")
    tot = f["total"] + h["total"]
    ref_tot = row.co2 + row.ch4 + row.n2o + row.other_wmghg
    lines.append(f"| **Total WMGHG** | {tot:.3f} | {ref_tot:.3f} | {tot - ref_tot:+.4f} |")
    f2x = co2_forcing(2 * PI["CO2"])
    lines += ["", f"2xCO2 ERF: {float(f2x):.3f} W m-2 (AR6: 3.93 +/- 0.47).", ""]
    yrs = conc.loc[1850:2019].index
    c = conc.loc[yrs]
    s = wmghg_forcing(c.CO2.values, c.CH4.values, c.N2O.values)
    lines += ["## Whole-series agreement 1850-2019 (max |error|, W m-2)", ""]
    for g, col in (("CO2", "co2"), ("CH4", "ch4"), ("N2O", "n2o")):
        lines.append(f"* {g}: {np.abs(s[g] - ar6.loc[yrs, col].values).max():.4f}")
    cols = {"O3": "o3", "H2O_strat": "h2o_stratospheric", "Aerosol_ari": "aerosol-radiation_interactions",
            "Aerosol_aci": "aerosol-cloud_interactions", "BC_snow": "bc_on_snow"}
    series = {k: [] for k in cols}
    for y in range(1750, 2020):
        r = non_ghg_erf(historical_state(y))
        for k in cols:
            series[k].append(r[k])
    lines += ["", "## Non-GHG emulators vs the AR6 series 1750-2019 (max |error|, W m-2)", "",
              "| Agent | max error | AR6 2019 |", "|---|---|---|"]
    for k, c in cols.items():
        err = np.abs(np.array(series[k]) - ar6.loc[1750:2019, c].values).max()
        lines.append(f"| {k} | {err:.4f} | {ar6.loc[2019, c]:.3f} |")
    lines += ["", "Aerosol-cloud shape factors are a least-squares fit to the AR6 median series (see `constants.py`).",
              f"\nSkipped halogenated species (no RE or no 2019 concentration): {', '.join(h['skipped'])}.", ""]
    spec = Path(__file__).resolve().parents[1] / "web/public/data/spectra/olr.json"
    halo_f = Path(__file__).resolve().parents[1] / "web/public/data/spectra/olr_halo.json"
    if spec.exists() and halo_f.exists():
        o = json.loads(spec.read_text())
        h = json.loads(halo_f.read_text())
        c = o["cloud"]
        e = {x["value"]: x for x in o["sweeps"]["CO2"]["entries"]}
        irf = lambda g, v, k="irf": next(x[k] for x in o["sweeps"][g]["entries"] if abs(x["value"] - v) < 1e-6)
        clear_now = o["baseline"]["olr"] - o["all_2019"]["irf"]
        all_now = o["baseline"]["olr_all"] - o["all_2019"]["irf_all"]
        ratios = np.array([v["re_all"] / v["re_ar6"] for v in h["gases"].values()])
        lines += ["", "## Spectral module (line-by-line + HITRAN cross-sections, MT_CKD continuum, US-standard atmosphere)", "",
                  "### Comparison with observation (independent of the model tuning)", "",
                  "| Quantity | model | observed | source |", "|---|---|---|---|",
                  f"| clear-sky OLR, present day | {clear_now:.1f} W m-2 | {c['ceres_clear_olr']} | CERES EBAF Ed4.0 (Loeb et al. 2018, Table 5) |",
                  f"| all-sky OLR, present day | {all_now:.1f} W m-2 | {c['ceres_allsky_olr']} | same |",
                  f"| longwave cloud radiative effect | {c['model_lw_cre']:.1f} W m-2 | {c['target_lw_cre']} | same (**this is the tuning target**) |",
                  "", "A single US-standard profile is not a global mean, so differences of a few W m-2 are expected.  Without the "
                  "water-vapour continuum and the 25 cm-1 line cut-off the model clear-sky OLR was 275 W m-2, 7 W m-2 too high.", "",
                  "### Cloud model", "",
                  f"All-sky = (1 - {c['cover']}) x clear + {c['cover']} x [grey deck at {c['deck_km'][0]:.0f}-{c['deck_km'][1]:.0f} km, optical depth "
                  f"{c['tau_c']:.3f}].  Cover is the satellite global-mean cloud fraction; the opacity is the single tuned parameter; the deck height is an "
                  "assumption (sensitivity in `docs/cloud_sensitivity.md`).", "",
                  "### Greenhouse-gas forcing (instantaneous, top of atmosphere, vs 1750 atmosphere)", "",
                  f"* 2xCO2: {e[556.6]['irf'] - e[278.3]['irf']:.2f} W m-2 clear sky, {e[556.6]['irf_all'] - e[278.3]['irf_all']:.2f} all-sky "
                  f"(AR6 effective forcing 3.93, which includes stratospheric adjustment).",
                  f"* Successive CO2 doublings add {irf('CO2', 556.6) - irf('CO2', 278.3):.2f}, {irf('CO2', 1113.2) - irf('CO2', 556.6):.2f} and "
                  f"{irf('CO2', 2226.4) - irf('CO2', 1113.2):.2f} W m-2 (clear sky): logarithmic law from line physics.",
                  f"* 1750 to 2019, all-sky estimate: CO2 {irf('CO2', 409.85, 'irf_all'):.2f}, CH4 {irf('CH4', 1866.3, 'irf_all'):.2f}, "
                  f"N2O {irf('N2O', 332.1, 'irf_all'):.2f}, all three {o['all_2019']['irf_all']:.2f} W m-2.", "",
                  "### Halocarbons (17 molecules, HITRAN cross-sections)", "",
                  f"All-sky radiative efficiency / AR6 Table 7.SM.7: {ratios.min():.2f}-{ratios.max():.2f}, mean {ratios.mean():.2f} "
                  f"(clear sky: {np.min([v['re_clear'] / v['re_ar6'] for v in h['gases'].values()]):.2f}-"
                  f"{np.max([v['re_clear'] / v['re_ar6'] for v in h['gases'].values()]):.2f}).  Full table: `docs/halocarbon_check.md`.  "
                  "The AR6 values were not used in tuning.  The remaining excess over AR6 is plausibly due to the single-profile, uniform-vertical-"
                  "distribution and one-deck cloud simplifications; stratospheric adjustment would push our values the other way, so it does not explain it."]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
