"""Loaders for the bundled, source-tracked datasets (see data/MANIFEST.md)."""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path

import pandas as pd

DATA_DIR = Path(__file__).resolve().parents[2] / "data"
RAW = DATA_DIR / "raw" / "ar6"
PROCESSED = DATA_DIR / "processed"


@lru_cache(maxsize=None)
def ar6_erf(quantile: str = "best") -> pd.DataFrame:
    """AR6 WG1 Ch.7 effective-radiative-forcing time series 1750-2019 (W m-2).

    ``quantile``: ``"best"`` (median), ``"pc05"`` or ``"pc95"`` (5th/95th
    percentile of the AR6 forcing ensemble).  Indexed by year.  Natural forcings
    (``volcanic``, ``solar``) are included; the 1750 value is not zero for them
    because their reference is a multi-century mean, not 1750 itself.

    ``total_anthropogenic`` equals the sum of co2, ch4, n2o, other_wmghg, o3,
    h2o_stratospheric, contrails, aerosol-radiation_interactions,
    aerosol-cloud_interactions, bc_on_snow and land_use (best estimate only);
    ``chapter2_other_anthro`` is a separate residual item not in that total.
    Percentile series are not additive.
    """
    name = {"best": "AR6_ERF_1750-2019.csv",
            "pc05": "AR6_ERF_1750-2019_pc05.csv",
            "pc95": "AR6_ERF_1750-2019_pc95.csv"}[quantile]
    return pd.read_csv(RAW / name).set_index("year")


@lru_cache(maxsize=None)
def ar6_minor_ghg_erf() -> pd.DataFrame:
    """AR6 ERF (W m-2) of each halogenated / minor GHG, 1750-2019."""
    return pd.read_csv(RAW / "AR6_ERF_minorGHGs_1750-2019.csv").set_index("year")


@lru_cache(maxsize=None)
def ar6_concentrations() -> pd.DataFrame:
    """AR6 Annex III global-mean GHG mixing ratios (1750, 1850-2019).

    CO2 in ppm, CH4 and N2O in ppb, all halogenated species in ppt.
    Generated by ``build/extract_ar6_concentrations.py``.
    """
    return pd.read_csv(PROCESSED / "ar6_ghg_concentrations.csv").set_index("year")


@lru_cache(maxsize=None)
def ar6_metrics() -> pd.DataFrame:
    """AR6 Table 7.SM.7: lifetimes, radiative efficiencies, GWP/GTP.

    Indexed by acronym (or formula where no acronym exists).  The AR6 repo
    README warns that CFC-11/CFC-12 values in the printed table were wrong; this
    cleaned version carries the corrected numbers.
    """
    m = pd.read_csv(RAW / "metrics_supplement_cleaned.csv")
    m["key"] = m["Acronym"].fillna(m["Formula"])
    return m.drop_duplicates("key").set_index("key")
